// i18nシステムを初期化
(function () {
	// 現在の言語を取得（デフォルト: jp）
	let currentLang = localStorage.getItem('lang') || 'jp';

	// 言語を設定する関数
	function setLanguage(lang) {
		currentLang = lang;
		localStorage.setItem('lang', lang);

		// すべてのdata-i18n要素を更新
		const elements = document.querySelectorAll('[data-i18n]');

		elements.forEach(element => {
			const key = element.getAttribute('data-i18n');
			if (translations[key] && translations[key][lang]) {
				// HTMLコンテンツの場合（<br>タグなどを含む）
				if (translations[key][lang].includes('<br')) {
					element.innerHTML = translations[key][lang];
				} else {
					element.textContent = translations[key][lang];
				}
			}
		});

		// placeholder属性の翻訳
		const placeholderElements = document.querySelectorAll('[data-i18n-placeholder]');
		placeholderElements.forEach(element => {
			const key = element.getAttribute('data-i18n-placeholder');
			if (translations[key] && translations[key][lang]) {
				element.setAttribute('placeholder', translations[key][lang]);
			}
		});

		// 言語切り替えボタンのテキストを更新
		const langBtn = document.getElementById('lang-switch-btn');
		if (langBtn) {
			langBtn.textContent = lang === 'jp' ? 'EN' : 'JP';
			langBtn.setAttribute('aria-label', lang === 'jp' ? 'Switch to English' : '日本語に切り替え');
		}
	}

	// 言語切り替えボタンのイベントリスナーを設定
	function setupLanguageButton() {
		const langBtn = document.getElementById('lang-switch-btn');
		if (langBtn) {
			// 既存のリスナーを削除（重複防止）
			langBtn.replaceWith(langBtn.cloneNode(true));
			const newBtn = document.getElementById('lang-switch-btn');

			newBtn.addEventListener('click', (e) => {
				e.preventDefault();
				const newLang = currentLang === 'jp' ? 'en' : 'jp';
				setLanguage(newLang);
			});
		}
	}

	// 初期化関数
	function initialize() {
		setLanguage(currentLang);
		setupLanguageButton();
	}

	// DOMContentLoadedで初期化
	if (document.readyState === 'loading') {
		document.addEventListener('DOMContentLoaded', initialize);
	} else {
		// すでに読み込み完了している場合
		initialize();
	}

	// Astroのページ遷移にも対応（ViewTransitionsの場合）
	document.addEventListener('astro:page-load', () => {
		initialize();
	});
})();
